/** Готовый <svg> строкой. Размер в пикселях; label — подпись для экранного диктора. */
export function svg(name, { size = 24, label = '' } = {}) {
  const body = icons[name];
  if (!body) throw new Error(`Нет иконки: ${name}`);
  const a11y = label ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"` : 'aria-hidden="true"';
  const rest = Object.entries(attrs).filter(([k]) => k !== 'width' && k !== 'height').map(([k, v]) => `${k}="${v}"`).join(' ');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ${rest} ${a11y}>${body}</svg>`;
}
